def soma (n1, n2) :
    return n1 + n2

def subttracao(n1, n2) :
    return n1 - n2

def divisao (n1, n2) :
    return n1 / n2

def multiplicacao (n1, n2) :
    return n1 * n2

def receber_numeros (n1, n2) :
    n1 = int(input("Insira o primeiro numero : "))
    n2 = int(input("Insira o segundo numero : "))
    return n1, n2